-- de chuva (nem mm, nem probabilidade) e nenhum instante de emissão (só o campo "hora", sem data nem fuso).
-- Fuso: as datas são datas civis no horário oficial de Brasília (America/Sao_Paulo, UTC-3 desde 2019, igual a Recife).

INSERT INTO source_registry (source, source_tz, verification_state, max_age_minutes, note)
VALUES (
    'INMET_PREVISAO',
    'America/Sao_Paulo',
    'DECLARED',
    720,
    'Previsão do tempo do INMET por município (apiprevmet3.inmet.gov.br/previsao/{ibge}), coletada a cada 3 h. Sem quantidade de chuva e sem hora de emissão: first_seen_at registra o primeiro instante em que o MAPi viu cada versão. Informação oficial, exibida como INMET; não entra em nenhum modelo do MAPi.'
)
ON CONFLICT (source) DO NOTHING;

-- Cada versão vista é uma linha (nada é sobrescrito): a mesma previsão vista de novo só avança last_seen_at.
CREATE TABLE official_forecast (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source          VARCHAR(30)  NOT NULL DEFAULT 'INMET_PREVISAO' REFERENCES source_registry (source),
    ibge            VARCHAR(7)   NOT NULL,
    municipality    VARCHAR(120),
    uf              VARCHAR(2),
    forecast_date   DATE         NOT NULL,
    period          VARCHAR(10)  NOT NULL CHECK (period IN ('MANHA', 'TARDE', 'NOITE', 'DIA')),
    summary         TEXT,
    weather         TEXT,
    icon_code       VARCHAR(10),
    temp_max        NUMERIC(5, 1),
    temp_min        NUMERIC(5, 1),
    humidity_max    NUMERIC(5, 1),
    humidity_min    NUMERIC(5, 1),
    wind_dir        VARCHAR(20),
    wind_intensity  VARCHAR(80),
    temp_max_trend  VARCHAR(60),
    temp_min_trend  VARCHAR(60),
    issue_hour_text VARCHAR(10),
    -- qualquer campo de chuva que a origem trouxer (hoje nenhum); guardado como veio, sem conversão
    rain_fields     JSONB        NOT NULL DEFAULT '{}'::jsonb,
    entry_hash      CHAR(64)     NOT NULL,
    raw_hash        CHAR(64)     NOT NULL,
    first_seen_at   TIMESTAMPTZ  NOT NULL,
    last_seen_at    TIMESTAMPTZ  NOT NULL,
    run_id          UUID         REFERENCES ingestion_run (id),
    CONSTRAINT official_forecast_unique UNIQUE (source, ibge, forecast_date, period, entry_hash)
);

CREATE INDEX idx_official_forecast_lookup ON official_forecast (ibge, forecast_date, period, last_seen_at DESC);
