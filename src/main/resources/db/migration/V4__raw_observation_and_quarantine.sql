-- ADR 0006 (aprovado), passo V4: staging bruto append-only e quarentena. ADITIVA.

CREATE TABLE raw_observation (
    id             UUID         NOT NULL,
    ingested_at    TIMESTAMPTZ  NOT NULL,
    -- ordem de gravação dentro do mesmo instante; desempate de "versão mais recente" (extensão ao ADR)
    seq            BIGINT GENERATED ALWAYS AS IDENTITY,
    run_id         UUID         NOT NULL REFERENCES ingestion_run (id),
    source         VARCHAR(40)  NOT NULL,
    station_id     VARCHAR(120) NOT NULL,
    collected_at   TIMESTAMPTZ  NOT NULL,
    source_ts_text VARCHAR(80)  NOT NULL,
    source_ts_norm VARCHAR(40)  NOT NULL,
    source_tz      VARCHAR(40)  NOT NULL,
    payload        JSONB        NOT NULL,
    content_hash   CHAR(64)     NOT NULL,
    PRIMARY KEY (id, ingested_at)
);
SELECT create_hypertable('raw_observation', 'ingested_at', chunk_time_interval => INTERVAL '7 days');

-- A hypertable não aceita UNIQUE sem a coluna de partição: a unicidade é garantida pela regra de
-- escrita (hash contra a versão mais recente) sob pg_advisory_xact_lock(hashtext(source)).
CREATE INDEX idx_raw_identity_latest ON raw_observation (source, station_id, source_ts_norm, ingested_at DESC, seq DESC);
CREATE INDEX idx_raw_source_text ON raw_observation (source, station_id, source_ts_text, ingested_at DESC);
CREATE INDEX idx_raw_hash ON raw_observation (source, station_id, content_hash);
CREATE INDEX idx_raw_run ON raw_observation (run_id);

-- Append-only: a aplicação não faz UPDATE nem DELETE no bruto (drop_chunks e TRUNCATE administrativos
-- não disparam gatilho de linha e continuam possíveis, com aprovação).
CREATE FUNCTION raw_observation_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'raw_observation é append-only (ADR 0006): % negado', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_raw_observation_append_only
    BEFORE UPDATE OR DELETE ON raw_observation
    FOR EACH ROW EXECUTE FUNCTION raw_observation_append_only();

-- Sem FK para a hypertable (o TimescaleDB não aceita FK apontando para hypertable): raw_id +
-- raw_ingested_at identificam a versão do bruto.
CREATE TABLE ingestion_quarantine (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id           UUID         NOT NULL REFERENCES ingestion_run (id),
    raw_id           UUID         NOT NULL,
    raw_ingested_at  TIMESTAMPTZ  NOT NULL,
    rule_id          VARCHAR(40)  NOT NULL,
    rule_version     VARCHAR(40)  NOT NULL,
    reason           VARCHAR(40)  NOT NULL,
    detail           JSONB        NOT NULL DEFAULT '{}'::jsonb,
    quarantined_at   TIMESTAMPTZ  NOT NULL,
    resolved_at      TIMESTAMPTZ,
    resolution       VARCHAR(80)
);
CREATE INDEX idx_quarantine_raw ON ingestion_quarantine (raw_id, rule_id) WHERE resolved_at IS NULL;
CREATE INDEX idx_quarantine_open ON ingestion_quarantine (reason) WHERE resolved_at IS NULL;
