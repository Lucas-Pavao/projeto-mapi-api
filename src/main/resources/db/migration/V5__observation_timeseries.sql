-- ADR 0006 (aprovado), passo V5: série consolidada versionada em UTC (formato longo) e views.
-- ADITIVA. Sem compressão nem continuous aggregates (V8 adiada).

CREATE TABLE observation (
    source             VARCHAR(40)  NOT NULL,
    station_id         VARCHAR(120) NOT NULL,
    variable           VARCHAR(40)  NOT NULL,
    resolution         VARCHAR(10)  NOT NULL CHECK (resolution IN ('PT5M', 'PT10M', 'PT15M', 'PT1H', 'P1D', 'EVENT')),
    ts_utc             TIMESTAMPTZ  NOT NULL,
    value              DOUBLE PRECISION,
    unit               VARCHAR(20)  NOT NULL,
    qualifier          VARCHAR(20),
    interval_start_utc TIMESTAMPTZ  NOT NULL,
    quality_flag       VARCHAR(14)  NOT NULL DEFAULT 'OK' CHECK (quality_flag IN ('OK', 'GAP_BEFORE', 'IMPUTED_NONE')),
    revision           INTEGER      NOT NULL DEFAULT 1,
    status             VARCHAR(9)   NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'RETRACTED')),
    run_id             UUID         NOT NULL REFERENCES ingestion_run (id),
    raw_hash           CHAR(64)     NOT NULL,
    rule_version       VARCHAR(40)  NOT NULL,
    value_hash         CHAR(64)     NOT NULL,
    -- identidade do registro de origem (source_ts_norm), para que a revalidação saiba retirar linhas
    -- cuja chave natural mudou (extensão ao ADR)
    origin_ts_norm     VARCHAR(40)  NOT NULL,
    CONSTRAINT observation_natural_key UNIQUE (source, station_id, variable, resolution, ts_utc)
);
SELECT create_hypertable('observation', 'ts_utc', chunk_time_interval => INTERVAL '30 days');
CREATE INDEX idx_observation_origin ON observation (source, station_id, origin_ts_norm);
CREATE INDEX idx_observation_run ON observation (run_id);

CREATE TABLE observation_revision (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source               VARCHAR(40)  NOT NULL,
    station_id           VARCHAR(120) NOT NULL,
    variable             VARCHAR(40)  NOT NULL,
    resolution           VARCHAR(10)  NOT NULL,
    ts_utc               TIMESTAMPTZ  NOT NULL,
    revision             INTEGER      NOT NULL,
    value                DOUBLE PRECISION,
    unit                 VARCHAR(20),
    qualifier            VARCHAR(20),
    status               VARCHAR(9),
    run_id               UUID,
    raw_hash             CHAR(64),
    rule_version         VARCHAR(40),
    value_hash           CHAR(64),
    superseded_by_run_id UUID,
    superseded_at        TIMESTAMPTZ NOT NULL,
    reason               VARCHAR(20) NOT NULL
);
CREATE INDEX idx_obs_revision_key ON observation_revision (source, station_id, variable, resolution, ts_utc, revision);
CREATE INDEX idx_obs_revision_superseded ON observation_revision (superseded_by_run_id);

CREATE FUNCTION observation_revision_copy() RETURNS trigger AS $$
BEGIN
    INSERT INTO observation_revision
        (source, station_id, variable, resolution, ts_utc, revision, value, unit, qualifier, status,
         run_id, raw_hash, rule_version, value_hash, superseded_by_run_id, superseded_at, reason)
    VALUES
        (OLD.source, OLD.station_id, OLD.variable, OLD.resolution, OLD.ts_utc, OLD.revision, OLD.value, OLD.unit,
         OLD.qualifier, OLD.status, OLD.run_id, OLD.raw_hash, OLD.rule_version, OLD.value_hash,
         NEW.run_id, clock_timestamp(),
         CASE WHEN NEW.status = 'RETRACTED' THEN 'RETRACTED'
              WHEN OLD.status = 'RETRACTED' THEN 'REACTIVATED'
              ELSE 'VALUE_CHANGED' END);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_observation_revision
    AFTER UPDATE ON observation
    FOR EACH ROW EXECUTE FUNCTION observation_revision_copy();

-- Leituras usam apenas ACTIVE.
CREATE VIEW observation_current AS
SELECT * FROM observation WHERE status = 'ACTIVE';

-- Grade horária DETERMINÍSTICA (sem materialização). O instante da linha é o FIM do intervalo
-- (t-1h, t]: a subtração de 1 microssegundo faz a leitura em HH:00:00 exato pertencer à linha HH:00.
-- Soma para chuva incremental, última leitura para estados. Completude abaixo de min_completeness
-- (80% [sem fonte]) => value NULL. P1D e EVENT não entram na grade horária.
CREATE VIEW observation_hourly_v AS
WITH base AS (
    SELECT o.source, o.station_id, o.variable, o.resolution, o.unit, o.ts_utc, o.value, o.run_id, o.revision,
           o.quality_flag, c.hourly_aggregation, c.min_completeness,
           time_bucket('1 hour', o.ts_utc - interval '1 microsecond') + interval '1 hour' AS hour_end_utc,
           CASE o.resolution WHEN 'PT5M' THEN 12 WHEN 'PT10M' THEN 6 WHEN 'PT15M' THEN 4 ELSE 1 END AS n_expected
    FROM observation_current o
    JOIN variable_catalog c ON c.variable = o.variable
    WHERE o.resolution IN ('PT5M', 'PT10M', 'PT15M', 'PT1H')
      AND c.hourly_aggregation IN ('SUM', 'LAST')
      AND o.value IS NOT NULL
)
SELECT source, station_id, variable, resolution, hour_end_utc,
       CASE WHEN count(*) < min(n_expected) * min(min_completeness) THEN NULL
            WHEN min(hourly_aggregation) = 'SUM' THEN sum(value)
            ELSE (array_agg(value ORDER BY ts_utc DESC))[1] END AS value,
       (array_agg(unit ORDER BY ts_utc DESC))[1] AS unit,
       count(*)::int AS n_readings,
       min(n_expected) AS n_expected,
       count(*) < min(n_expected) * min(min_completeness) AS incomplete,
       bool_or(quality_flag <> 'OK') AS has_flag,
       array_agg(DISTINCT run_id) AS run_ids,
       max(revision) AS max_revision
FROM base
GROUP BY source, station_id, variable, resolution, hour_end_utc;
