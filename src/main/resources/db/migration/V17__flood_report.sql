-- Fila de relatos de alagamento (redesign, pergunta 3 da F0). Não é rótulo de treino nem ocorrência da
-- Defesa Civil: confirmar um relato cria um flood_events e NUNCA toca flood_occurrence.
CREATE TABLE flood_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    observed_at TIMESTAMPTZ NOT NULL,
    water_depth VARCHAR(20) CHECK (water_depth IN ('ANKLE', 'KNEE', 'WAIST', 'ABOVE_WAIST')),
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'CONFIRMED', 'DISCARDED')),
    reported_by VARCHAR(255) NOT NULL,
    nearest_point_id BIGINT REFERENCES flood_points(id) ON DELETE SET NULL,
    nearest_point_distance_m INTEGER,
    created_at TIMESTAMPTZ NOT NULL,
    reviewed_by VARCHAR(255),
    reviewed_at TIMESTAMPTZ,
    flood_event_id BIGINT REFERENCES flood_events(id) ON DELETE SET NULL,
    discard_reason TEXT
);
CREATE INDEX idx_flood_report_status_created ON flood_report (status, created_at DESC);
