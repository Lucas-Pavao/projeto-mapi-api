-- V30 — Previsão de chuva (plano de 16/11, fase 3). Só adição: duas visões, duas tabelas e uma fonte declarada.
-- DADOS DA REDE OBSERVACIONAL DO CEMADEN/MCTIC.

-- Blocos de chuva por estação canônica. Por estação e hora, vale UMA fonte: a PED quando tem bloco naquela hora;
-- senão a coleta ao vivo da mesma estação física. Evita somar o mesmo intervalo duas vezes.
CREATE VIEW canonical_rain_block_v AS
SELECT a.canonical_id, o.source, o.station_id, o.ts_utc, o.interval_start_utc, o.value
FROM observation_current o
JOIN station_alias a ON a.source = o.source AND a.station_id = o.station_id
WHERE o.variable = 'precipitation' AND o.value IS NOT NULL
  AND (o.source = 'CEMADEN_PED'
       OR (o.source = 'CEMADEN' AND NOT EXISTS (
            SELECT 1 FROM observation_current p
            JOIN station_alias pa ON pa.source = p.source AND pa.station_id = p.station_id
            WHERE pa.canonical_id = a.canonical_id AND p.source = 'CEMADEN_PED' AND p.variable = 'precipitation'
              AND p.value IS NOT NULL
              AND p.ts_utc >  time_bucket('1 hour', o.ts_utc - interval '1 microsecond')
              AND p.ts_utc <= time_bucket('1 hour', o.ts_utc - interval '1 microsecond') + interval '1 hour')));

-- Vizinhança de cada ponto: estações canônicas da PED a até 40 km, com distância, setor (N, S, L, O) e anel.
-- Só as de origem PED, as mesmas 46 do treino do modelo de chuva (rain_v1).
CREATE VIEW point_rain_neighbors_v AS
SELECT f.id AS flood_point_id, f.slug, c.canonical_id, c.name, c.lat, c.lon, d.km,
       d.km <= 5.0 AS near,
       CASE WHEN d.km <= 5.0 THEN '0-5' WHEN d.km <= 15.0 THEN '5-15' ELSE '15-40' END AS ring,
       CASE WHEN ang >= -45 AND ang < 45 THEN 'L' WHEN ang >= 45 AND ang < 135 THEN 'N'
            WHEN ang >= -135 AND ang < -45 THEN 'S' ELSE 'O' END AS sector
FROM flood_points f
CROSS JOIN station_canonical c
CROSS JOIN LATERAL (SELECT ST_DistanceSphere(ST_MakePoint(f.longitude, f.latitude), ST_MakePoint(c.lon, c.lat)) / 1000.0 AS km,
                           degrees(atan2(c.lat - f.latitude, (c.lon - f.longitude) * cos(radians(f.latitude)))) AS ang) d
WHERE c.primary_source = 'CEMADEN_PED' AND d.km <= 40.0;

-- Previsão do Open-Meteo, rodada da véspera (previous-runs-api, precipitation_previous_day1). Fonte declarada e
-- SEPARADA da reanálise. issued_before_utc: a rodada foi emitida até esse instante (24 h antes da hora prevista);
-- na montagem das entradas só vale o que foi emitido até t.
CREATE TABLE open_meteo_forecast_hour (
    flood_point_id    BIGINT      NOT NULL REFERENCES flood_points (id),
    hour_end_utc      TIMESTAMPTZ NOT NULL,
    product           VARCHAR(40) NOT NULL DEFAULT 'previous_day1',
    mm                DOUBLE PRECISION,
    issued_before_utc TIMESTAMPTZ NOT NULL,
    grid_lat          DOUBLE PRECISION,
    grid_lon          DOUBLE PRECISION,
    raw_hash          CHAR(64)    NOT NULL,
    fetched_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (flood_point_id, hour_end_utc, product)
);

INSERT INTO source_registry (source, source_tz, verification_state, note)
VALUES ('OPEN_METEO_FORECAST', 'UTC', 'DECLARED',
        'Previsão do Open-Meteo, rodada da véspera (previous-runs-api, timezone=UTC pedido na consulta). É PREVISÃO, não medição nem reanálise. Guardada em open_meteo_forecast_hour, fora de observation.')
ON CONFLICT (source) DO NOTHING;

-- Cada previsão de chuva emitida, para conferência posterior contra a chuva medida.
CREATE TABLE rain_forecast (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flood_point_id      BIGINT      NOT NULL REFERENCES flood_points (id),
    issued_at           TIMESTAMPTZ NOT NULL,
    horizon_hours       INTEGER     NOT NULL,
    valid_until         TIMESTAMPTZ NOT NULL,
    q50_mm              DOUBLE PRECISION NOT NULL,
    q80_mm              DOUBLE PRECISION NOT NULL,
    q95_mm              DOUBLE PRECISION NOT NULL,
    prob_media          DOUBLE PRECISION NOT NULL,
    prob_forte          DOUBLE PRECISION NOT NULL,
    forte_alert         BOOLEAN     NOT NULL,
    model_version       VARCHAR(40) NOT NULL,
    model               VARCHAR(40) NOT NULL,
    sources             JSONB       NOT NULL DEFAULT '[]'::jsonb,
    missing_inputs      JSONB       NOT NULL DEFAULT '[]'::jsonb,
    latest_reading_utc  TIMESTAMPTZ,
    latest_reading_age_min DOUBLE PRECISION,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- conferência (job diário): chuva medida no ponto em (issued_at, valid_until]; NULL = ainda não conferida ou sem medida
    observed_mm         DOUBLE PRECISION,
    observed_peak_mm_h  DOUBLE PRECISION,
    verified_at         TIMESTAMPTZ,
    verification_note   VARCHAR(40),
    UNIQUE (flood_point_id, issued_at, horizon_hours)
);
CREATE INDEX idx_rain_forecast_pending ON rain_forecast (valid_until) WHERE verified_at IS NULL;
CREATE INDEX idx_rain_forecast_point ON rain_forecast (flood_point_id, issued_at DESC);
