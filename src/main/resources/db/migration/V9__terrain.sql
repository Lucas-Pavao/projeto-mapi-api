-- V9: terreno do PE3D por ponto critico (ADR 0008, aprovado em 2026-10-10; referencia vertical: ADR 0009).
-- Aditiva: apenas CREATE TABLE / CREATE INDEX. Nenhuma coluna de mare ou folga (depende do Delta do ADR 0009).

CREATE TABLE terrain_run (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    vrt_sha256             CHAR(64)    NOT NULL,
    script_sha256          CHAR(64)    NOT NULL,
    gdal_image_digest      TEXT        NOT NULL,
    software_versions      JSONB       NOT NULL,
    sheets                 TEXT[]      NOT NULL,
    parameters             JSONB       NOT NULL,
    flight_year            SMALLINT    NOT NULL,
    vertical_reference     TEXT        NOT NULL,
    vertical_reference_adr TEXT,
    raster_manifest        JSONB,
    raster_sha256          CHAR(64),
    current                BOOLEAN     NOT NULL DEFAULT FALSE
);

-- uma so execucao vigente
CREATE UNIQUE INDEX terrain_run_one_current_uq ON terrain_run (current) WHERE current;

-- idempotencia da carga: o hash dos arquivos de entrada fica em parameters ('inputSha256')
CREATE UNIQUE INDEX terrain_run_input_sha256_uq ON terrain_run ((parameters ->> 'inputSha256'))
    WHERE parameters ? 'inputSha256';

COMMENT ON COLUMN terrain_run.vertical_reference IS 'Datum vertical do MDT declarado, sem delta para a mare (ADR 0009)';

CREATE TABLE point_terrain (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flood_point_id        BIGINT           NOT NULL REFERENCES flood_points (id),
    run_id                BIGINT           NOT NULL REFERENCES terrain_run (id),
    status                TEXT             NOT NULL CHECK (status IN ('OK', 'NO_DATA')),
    source_sheet          TEXT,
    street_elevation_m    DOUBLE PRECISION,
    elevation_pixel_count SMALLINT,
    mean_slope_pct        DOUBLE PRECISION,
    max_slope_pct         DOUBLE PRECISION,
    depression_depth_m    DOUBLE PRECISION,
    contributing_area_m2  DOUBLE PRECISION,
    bottom_elevation_m    DOUBLE PRECISION,
    bottom_distance_m     DOUBLE PRECISION,
    diagnostics           JSONB,
    created_at            TIMESTAMPTZ      NOT NULL DEFAULT now(),
    CONSTRAINT point_terrain_point_run_uq UNIQUE (flood_point_id, run_id),
    CONSTRAINT point_terrain_no_data_nulls CHECK (status = 'OK' OR (
        street_elevation_m IS NULL AND mean_slope_pct IS NULL AND max_slope_pct IS NULL
        AND depression_depth_m IS NULL AND contributing_area_m2 IS NULL
        AND bottom_elevation_m IS NULL AND bottom_distance_m IS NULL))
);

CREATE INDEX point_terrain_run_idx ON point_terrain (run_id);

CREATE TABLE point_terrain_curve (
    point_terrain_id     BIGINT           NOT NULL REFERENCES point_terrain (id) ON DELETE CASCADE,
    above_bottom_cm      SMALLINT         NOT NULL,
    elevation_m          DOUBLE PRECISION NOT NULL,
    cumulative_volume_m3 DOUBLE PRECISION NOT NULL,
    -- nulo no nivel 0 (dV/dh indefinido no fundo; o CSV de origem vem vazio ali)
    m3_per_cm            DOUBLE PRECISION,
    wet_area_m2          DOUBLE PRECISION,
    PRIMARY KEY (point_terrain_id, above_bottom_cm)
);
