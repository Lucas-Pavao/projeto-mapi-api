INSERT INTO source_registry (source, source_tz, verification_state, max_age_minutes, note)
VALUES (
    'INMET_AVISOS',
    'America/Sao_Paulo',
    'DECLARED',
    30,
    'Avisos severos do INMET (apiprevmet3.inmet.gov.br/avisos/ativos). Sem timestamp de emissão na origem (created_at/updated_at trazem só data): first_seen_at registra o primeiro instante em que o MAPi observou (warning_id, sequence_id). Não entra no modelo de alagamento nem no rain_v1.'
)
ON CONFLICT (source) DO NOTHING;

CREATE TABLE official_warning (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source            VARCHAR(30)      NOT NULL DEFAULT 'INMET_AVISOS' REFERENCES source_registry (source),
    warning_id        INTEGER          NOT NULL,
    sequence_id       INTEGER          NOT NULL,
    external_id       INTEGER,
    cap_code          VARCHAR(120),
    first_seen_at     TIMESTAMPTZ      NOT NULL,
    last_seen_at      TIMESTAMPTZ      NOT NULL,
    valid_from        TIMESTAMPTZ      NOT NULL,
    valid_to          TIMESTAMPTZ      NOT NULL,
    severity          VARCHAR(60)      NOT NULL,
    severity_id       INTEGER,
    color_hex         VARCHAR(16),
    description       TEXT,
    risks             TEXT[]           NOT NULL DEFAULT '{}'::text[],
    instructions      TEXT[]           NOT NULL DEFAULT '{}'::text[],
    geocodes          TEXT[]           NOT NULL DEFAULT '{}'::text[],
    municipalities    TEXT,
    polygon_geojson   JSONB,
    altered           BOOLEAN          NOT NULL DEFAULT false,
    closed            BOOLEAN          NOT NULL DEFAULT false,
    raw_hash          CHAR(64)         NOT NULL,
    run_id            UUID             REFERENCES ingestion_run (id),
    CONSTRAINT official_warning_unique UNIQUE (source, warning_id, sequence_id)
);

CREATE INDEX idx_official_warning_valid ON official_warning (valid_to DESC, closed);
CREATE INDEX idx_official_warning_geocodes ON official_warning USING GIN (geocodes);
