-- V44 — Conferência semanal do rain_v1 contra a persistência (onda 16, Fase 1.1). Só adição.
-- Uma linha por semana (ou acumulado do trecho), prazo e trecho (antes/depois de cada quebra de série que afeta o rain_v1).
-- Regra do status em docs/PRE-REGISTRO-CONFERENCIA-SEMANAL-RAIN.md.
CREATE TABLE rain_forecast_check (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope                VARCHAR(12)      NOT NULL CHECK (scope IN ('SEMANA', 'TRECHO')),
    period_from          TIMESTAMPTZ      NOT NULL,
    period_to            TIMESTAMPTZ      NOT NULL,
    segment              VARCHAR(60)      NOT NULL,          -- ex.: "antes de 2026-11-30", "depois de 2026-11-30"
    horizon_hours        INTEGER          NOT NULL,
    n_forecasts          INTEGER          NOT NULL,
    n_days               INTEGER          NOT NULL,
    n_rain_days          INTEGER          NOT NULL,
    pinball_model        DOUBLE PRECISION,
    pinball_persistence  DOUBLE PRECISION,
    skill                DOUBLE PRECISION,
    skill_lo             DOUBLE PRECISION,
    skill_hi             DOUBLE PRECISION,
    test_skill           DOUBLE PRECISION NOT NULL,
    test_skill_lo        DOUBLE PRECISION NOT NULL,
    test_skill_hi        DOUBLE PRECISION NOT NULL,
    status               VARCHAR(12)      NOT NULL CHECK (status IN ('OK', 'PIORA', 'POUCO_DADO')),
    rule_version         VARCHAR(40)      NOT NULL,
    computed_at          TIMESTAMPTZ      NOT NULL DEFAULT now(),
    CONSTRAINT rain_forecast_check_unique UNIQUE (scope, period_from, period_to, segment, horizon_hours, rule_version)
);
CREATE INDEX idx_rain_forecast_check_recent ON rain_forecast_check (computed_at DESC);
