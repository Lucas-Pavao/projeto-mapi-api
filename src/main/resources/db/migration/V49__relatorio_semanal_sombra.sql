-- V49 — Relatório semanal do modo sombra (onda 16, Fase 9.4). Só adição.
-- Uma linha por semana local (segunda a segunda, America/Recife) e ponto: ciclos feitos contra esperados, buracos sem ciclo,
-- ciclos por nível, SEM_DADO por motivo e episódios de alerta. Regra em docs/PRE-REGISTRO-VALIDACAO-2027.md (seções 2, 7 e 9).
-- labels_status fica 'LACRADOS' até o fim do período de validação: nada aqui é comparado com rótulo de alagamento.
CREATE TABLE shadow_weekly_report (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_from                   TIMESTAMPTZ  NOT NULL,
    week_to                     TIMESTAMPTZ  NOT NULL,
    flood_point_id              BIGINT       NOT NULL REFERENCES flood_points(id) ON DELETE CASCADE,
    slug                        VARCHAR(255) NOT NULL,
    n_cycles                    INTEGER      NOT NULL,
    n_expected                  INTEGER      NOT NULL,
    longest_gap_min             INTEGER      NOT NULL,
    gaps_over_30min             INTEGER      NOT NULL,
    by_level                    JSONB        NOT NULL,
    sem_dado_by_reason          JSONB        NOT NULL,
    alerta_episodes             INTEGER      NOT NULL,
    alerta_ou_atencao_episodes  INTEGER      NOT NULL,
    labels_status               VARCHAR(20)  NOT NULL DEFAULT 'LACRADOS' CHECK (labels_status IN ('LACRADOS', 'ABERTOS')),
    rule_version                VARCHAR(40)  NOT NULL,
    computed_at                 TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT shadow_weekly_report_unique UNIQUE (week_from, flood_point_id, rule_version)
);
CREATE INDEX idx_shadow_weekly_report_week ON shadow_weekly_report (week_from DESC);
