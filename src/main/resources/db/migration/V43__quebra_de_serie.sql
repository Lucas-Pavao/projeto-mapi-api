-- V43 — Quebras de série das fontes (onda 16, Fase 1.1). Só adição.
-- Uma quebra é um instante em que a fonte muda por dentro (modelo, grade, obra) sem mudar de nome. Toda avaliação e toda
-- conferência separa o antes e o depois de cada quebra que afeta o que está sendo medido.
CREATE TABLE source_series_break (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source            VARCHAR(40)  NOT NULL REFERENCES source_registry (source),
    model             VARCHAR(40),                         -- nulo = a fonte inteira
    break_at          TIMESTAMPTZ  NOT NULL,
    kind              VARCHAR(40)  NOT NULL,               -- MUDANCA_DE_MODELO, MUDANCA_DE_GRADE, ...
    description       TEXT         NOT NULL,
    evidence_url      TEXT,
    evidence_accessed DATE,
    affects           TEXT[]       NOT NULL DEFAULT '{}',  -- o que depende do trecho (ex.: rain_v1)
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT source_series_break_unique UNIQUE (source, model, break_at, kind)
);

