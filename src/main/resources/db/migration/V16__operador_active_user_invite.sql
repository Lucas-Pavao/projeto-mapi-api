-- ADR 0010: perfil OPERADOR, usuário ativo/inativo e convite de uso único.
-- Aditivo: só troca o CHECK de users.role (incluindo OPERADOR) e acrescenta colunas/tabela.

ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('USER', 'OPERADOR', 'ADMIN'));

ALTER TABLE users ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE users ADD COLUMN last_login_at TIMESTAMPTZ;

-- O token em claro só existe na resposta da criação; o banco guarda o SHA-256 (hex).
CREATE TABLE user_invite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    role VARCHAR(20) NOT NULL CHECK (role IN ('USER', 'OPERADOR', 'ADMIN')),
    email VARCHAR(255),
    created_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    used_by VARCHAR(255)
);
CREATE INDEX idx_user_invite_expires ON user_invite (expires_at);
