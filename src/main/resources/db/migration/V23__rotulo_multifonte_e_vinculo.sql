-- ADR 0019 (aprovado em 2026-11-08): rótulo de alagamento multifonte, com precisão e confiança declaradas.
-- ADR 0018 (aprovado em 2026-11-08): vínculo estação↔ponto com raio máximo de 5 km.
-- ADR 0020 (aprovado em 2026-11-08): APAC histórica diária como fonte nova.
-- ADITIVA: só ADD COLUMN, CREATE TABLE e INSERT de configuração. Nenhuma linha existente é apagada.

-- 1. flood_occurrence ganha fonte, precisão espacial, confiança, tipo e identificador de origem.
ALTER TABLE flood_occurrence
    ADD COLUMN source VARCHAR(20) NOT NULL DEFAULT 'CKAN_RECIFE'
        CONSTRAINT flood_occurrence_source_chk CHECK (source IN
            ('CKAN_RECIFE', 'EMLURB_156', 'DEFESA_CIVIL_LAI', 'BOMBEIROS_PE', 'IMPRENSA', 'OUTRA'));

-- Tipo pelo código oficial (Cobrade). Os registros atuais passaram pelo label_filter "cobrade-alagamento" (V6),
-- que só aceita alagamento; por isso o padrão é ALAGAMENTO. Fontes novas gravam o tipo explicitamente.
ALTER TABLE flood_occurrence
    ADD COLUMN event_type VARCHAR(10) NOT NULL DEFAULT 'ALAGAMENTO'
        CONSTRAINT flood_occurrence_event_type_chk CHECK (event_type IN ('ALAGAMENTO', 'ENXURRADA', 'INUNDACAO'));

-- Precisão temporal passa a aceitar MINUTE (a coluna era VARCHAR(4)).
ALTER TABLE flood_occurrence DROP CONSTRAINT flood_occurrence_temporal_precision_check;
ALTER TABLE flood_occurrence ALTER COLUMN temporal_precision TYPE VARCHAR(6);
ALTER TABLE flood_occurrence ADD CONSTRAINT flood_occurrence_temporal_precision_check
    CHECK (temporal_precision IN ('MINUTE', 'HOUR', 'DAY'));

-- Precisão espacial derivada, nunca escrita à mão: coordenada da própria fonte, ou nível da geocodificação (V11).
ALTER TABLE flood_occurrence ADD COLUMN spatial_precision VARCHAR(10) GENERATED ALWAYS AS (
    CASE
        WHEN geocode_method = 'SOURCE_COORDINATE' THEN 'COORDENADA'
        WHEN geocode_level = 'STREET' THEN 'LOGRADOURO'
        WHEN geocode_level = 'NEIGHBORHOOD' THEN 'BAIRRO'
        WHEN geocode_level = 'CITY' THEN 'MUNICIPIO'
        ELSE NULL
    END) STORED;

-- Confiança por regra fixa (ADR 0019, item 2), também derivada:
--   BAIXA: imprensa, 156 (indício indireto) ou local só no nível de bairro/município (ou desconhecido);
--   ALTA: fonte oficial com hora ou minuto e logradouro ou coordenada;
--   MEDIA: fonte oficial com dia e logradouro ou coordenada.
ALTER TABLE flood_occurrence ADD COLUMN confidence VARCHAR(5) GENERATED ALWAYS AS (
    CASE
        WHEN source IN ('IMPRENSA', 'EMLURB_156', 'OUTRA') THEN 'BAIXA'
        WHEN coalesce(geocode_method, '') <> 'SOURCE_COORDINATE' AND coalesce(geocode_level, '') <> 'STREET'
             THEN 'BAIXA'
        WHEN temporal_precision IN ('HOUR', 'MINUTE') THEN 'ALTA'
        ELSE 'MEDIA'
    END) STORED;

-- Identificador na fonte, para deduplicar entre fontes e reprocessar.
ALTER TABLE flood_occurrence ADD COLUMN origin_id VARCHAR(300) GENERATED ALWAYS AS (
    source || ':' || ckan_resource_id || ':' || ckan_record_id) STORED;

CREATE INDEX idx_flood_occurrence_day ON flood_occurrence (occurred_from);

-- 2. Deduplicação entre fontes: grupo derivado (recalculável), com a melhor precisão dos membros.
CREATE TABLE occurrence_cluster (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_day           DATE             NOT NULL,
    lat                 DOUBLE PRECISION,
    lon                 DOUBLE PRECISION,
    event_type          VARCHAR(10)      NOT NULL,
    temporal_precision  VARCHAR(6)       NOT NULL,
    spatial_precision   VARCHAR(10),
    confidence          VARCHAR(5)       NOT NULL,
    first_from          TIMESTAMPTZ      NOT NULL,
    sources             TEXT[]           NOT NULL,
    members             INTEGER          NOT NULL,
    rule_version        VARCHAR(40)      NOT NULL,
    built_at            TIMESTAMPTZ      NOT NULL DEFAULT now()
);
CREATE INDEX idx_occurrence_cluster_day ON occurrence_cluster (local_day);

CREATE TABLE occurrence_cluster_member (
    cluster_id    BIGINT NOT NULL REFERENCES occurrence_cluster (id) ON DELETE CASCADE,
    occurrence_id BIGINT NOT NULL REFERENCES flood_occurrence (id),
    PRIMARY KEY (cluster_id, occurrence_id)
);

-- 3. Negativos verificados, separados do "dia sem registro" (ADR 0019, item 4).
CREATE TABLE verified_negative (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flood_point_id BIGINT       NOT NULL REFERENCES flood_points (id),
    local_day      DATE         NOT NULL,
    origin         VARCHAR(30)  NOT NULL CHECK (origin IN ('DEFESA_CIVIL_CONFIRMACAO', 'FOTO_DATADA', 'AUSENCIA_DE_CHAMADO')),
    confidence     VARCHAR(5)   NOT NULL CHECK (confidence IN ('ALTA', 'MEDIA', 'BAIXA')),
    evidence       TEXT,
    run_id         UUID         REFERENCES ingestion_run (id),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT verified_negative_unique UNIQUE (flood_point_id, local_day, origin)
);

