-- ADR 0011: regras e alertas. alert_state guarda se cada (regra, alvo) estava "em condição" no ciclo anterior,
-- para alertar só na transição e sobreviver a reinício (emenda 1 do ADR 0011).
CREATE TABLE alert_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(30) NOT NULL CHECK (kind IN ('RISK_LEVEL', 'RIVER_STAGE', 'TIDE_ABOVE', 'RAIN_RATE', 'SENSOR_STALE', 'PREDICTION_UNAVAILABLE')),
    flood_point_id BIGINT REFERENCES flood_points(id) ON DELETE CASCADE,
    station_id VARCHAR(255),
    threshold DOUBLE PRECISION,
    threshold_source TEXT,
    min_risk VARCHAR(10) CHECK (min_risk IN ('MEDIUM', 'HIGH')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    channels VARCHAR(100) NOT NULL DEFAULT 'BROWSER',
    created_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ
);

CREATE TABLE alert (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id BIGINT REFERENCES alert_rule(id) ON DELETE SET NULL,
    kind VARCHAR(30) NOT NULL,
    severity VARCHAR(10) NOT NULL CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL')),
    flood_point_id BIGINT REFERENCES flood_points(id) ON DELETE SET NULL,
    station_id VARCHAR(255),
    title TEXT NOT NULL,
    detail TEXT,
    observed_value DOUBLE PRECISION,
    risk_level VARCHAR(10),
    degradation_reason VARCHAR(30),
    prediction_id BIGINT,
    model_validation_status VARCHAR(20),
    triggered_at TIMESTAMPTZ NOT NULL,
    acknowledged_at TIMESTAMPTZ,
    acknowledged_by VARCHAR(255)
);
CREATE INDEX idx_alert_triggered ON alert (triggered_at DESC);
CREATE INDEX idx_alert_rule_target ON alert (rule_id, flood_point_id, station_id, triggered_at DESC);

CREATE TABLE alert_state (
    rule_id BIGINT NOT NULL REFERENCES alert_rule(id) ON DELETE CASCADE,
    target_key VARCHAR(300) NOT NULL,
    in_condition BOOLEAN NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (rule_id, target_key)
);

