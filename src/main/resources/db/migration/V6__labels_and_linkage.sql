-- ADR 0006 (aprovado), passo V6: rótulos CKAN e vínculos. ADITIVA: só referencia flood_points(id).

CREATE TABLE linkage_config (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       VARCHAR(20) NOT NULL CHECK (kind IN ('SENSOR_POINT', 'OCCURRENCE_POINT')),
    radius_m   DOUBLE PRECISION NOT NULL CHECK (radius_m > 0),
    method     VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(80),
    note       TEXT
);

-- Filtro Cobrade como configuração gravada (decisão do autor: só "alagamento").
CREATE TABLE label_filter (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(80) NOT NULL,
    accepted_codes TEXT[] NOT NULL,
    accepted_texts TEXT[] NOT NULL DEFAULT '{}',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    note           TEXT
);

CREATE TABLE flood_occurrence (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ckan_package_id    VARCHAR(120),
    ckan_resource_id   VARCHAR(120) NOT NULL,
    ckan_record_id     VARCHAR(120) NOT NULL,
    raw_hash           CHAR(64) NOT NULL,
    run_id             UUID NOT NULL REFERENCES ingestion_run (id),
    revision           INTEGER NOT NULL DEFAULT 1,
    address_text       TEXT,
    occurred_from      TIMESTAMPTZ NOT NULL,
    occurred_to        TIMESTAMPTZ NOT NULL,
    temporal_precision VARCHAR(4) NOT NULL CHECK (temporal_precision IN ('HOUR', 'DAY')),
    cobrade_code       VARCHAR(20),
    cobrade_text       VARCHAR(255),
    geocoded_lat       DOUBLE PRECISION,
    geocoded_lon       DOUBLE PRECISION,
    geocode_method     VARCHAR(40),
    CONSTRAINT flood_occurrence_natural_key UNIQUE (ckan_resource_id, ckan_record_id)
);

CREATE TABLE occurrence_point_match (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurrence_id     BIGINT NOT NULL REFERENCES flood_occurrence (id),
    flood_point_id    BIGINT NOT NULL REFERENCES flood_points (id),
    distance_m        DOUBLE PRECISION NOT NULL,
    radius_m          DOUBLE PRECISION NOT NULL,
    linkage_config_id BIGINT NOT NULL REFERENCES linkage_config (id),
    method            VARCHAR(30) NOT NULL DEFAULT 'NEAREST_WITHIN_RADIUS',
    rule_version      VARCHAR(40) NOT NULL,
    matched_at        TIMESTAMPTZ NOT NULL,
    CONSTRAINT occurrence_match_unique UNIQUE (occurrence_id, flood_point_id, linkage_config_id)
);

CREATE TABLE point_station_link (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flood_point_id    BIGINT NOT NULL REFERENCES flood_points (id),
    source            VARCHAR(40) NOT NULL,
    station_id        VARCHAR(120) NOT NULL,
    variable_scope    VARCHAR(40) NOT NULL DEFAULT '*',
    distance_m        DOUBLE PRECISION NOT NULL,
    radius_m          DOUBLE PRECISION NOT NULL,
    linkage_config_id BIGINT NOT NULL REFERENCES linkage_config (id),
    method            VARCHAR(20) NOT NULL CHECK (method IN ('NEAREST', 'ALL_WITHIN')),
    valid_from        TIMESTAMPTZ NOT NULL DEFAULT now(),
    valid_to          TIMESTAMPTZ,
    FOREIGN KEY (source, station_id) REFERENCES station (source, station_id)
);
CREATE INDEX idx_point_station_link_point ON point_station_link (flood_point_id);

